#!/bin/sh
# Build the runtime: dn-init (the tracer, src/dn-init), dn-exec (the userland
# exec every program is handed, src/dn-exec), and the two programs that test and
# measure it, dn-substtest and dn-census.  All are aarch64 with no libc and no
# imports, so any C compiler that emits aarch64 code will do: Termux's clang, gcc
# on an arm64 Linux, or a cross compiler.  build-prefix.sh installs all three
# runtime binaries into usr/lib/deb-native/.
#
# dn-exec is host-independent: one binary serves an app prefix and an adb one,
# so it is built once into OUT whatever --host says.
#
# The shim, dn-lane.so, is not built here: it is linked against a glibc, so
# scripts/build-shim.sh builds it (--in-prefix PREFIX, or --cross), and
# build-prefix.sh only copies the result.
#
# The rows of the policy table (which syscalls are caught, where their path
# arguments are) are generated by src/dn-init/gen_rows.py, so python3 is needed.
#
# Usage: scripts/build-runtime.sh [--host app|adb] [OUTDIR]   (default: build/)
#   --host adb  the shell/ADB host: no Android seccomp filter, so the
#               app-domain answer table (policy_deny/SIGSYS) is compiled out;
#               the rows and the law are the same.  It must match the prefix's
#               boot/version (host=app or host=adb): an ADB prefix needs adb,
#               or the adb answers (the abstract AF_UNIX mapping among them)
#               are left out.  build/host records the choice.
#   CC          the compiler (default: clang, else gcc, else aarch64-linux-gnu-gcc)
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
SRC="$ROOT/src/dn-init"
HOST=app
while [ $# -gt 0 ]; do
  case $1 in
    --host) HOST=$2; shift 2 ;;
    -h|--help) sed -n '2,/^set -eu/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
    -*) echo "build-runtime: unknown option $1" >&2; exit 2 ;;
    *) break ;;
  esac
done
case $HOST in
  app) HOSTFLAGS= ;;
  adb) HOSTFLAGS=-DDN_HOST_ADB ;;
  *) echo "build-runtime: --host is app or adb" >&2; exit 2 ;;
esac
OUT=${1:-$ROOT/build}
mkdir -p "$OUT"
OUT=$(CDPATH= cd -- "$OUT" && pwd)

if [ -z "${CC:-}" ]; then
  for c in clang gcc aarch64-linux-gnu-gcc; do
    if command -v "$c" >/dev/null 2>&1; then CC=$c; break; fi
  done
fi
[ -n "${CC:-}" ] && command -v "$CC" >/dev/null 2>&1 || { echo "build-runtime: no C compiler (set CC)" >&2; exit 1; }
case "$("$CC" -dumpmachine)" in
  aarch64-*) ;;
  *) echo "build-runtime: $CC targets $("$CC" -dumpmachine), not aarch64 (set CC to a cross compiler)" >&2; exit 1 ;;
esac
command -v python3 >/dev/null 2>&1 || { echo "build-runtime: python3 not found (it generates the policy rows)" >&2; exit 1; }

FLAGS="-O2 -Wall -Wextra -static -nostdlib -ffreestanding -fno-builtin -fno-stack-protector
 -fno-asynchronous-unwind-tables -fno-pie -Wl,-z,noexecstack $HOSTFLAGS"
# gcc would turn a copy loop into a call to memcpy, which does not exist here
if echo 'int x;' | "$CC" -fno-tree-loop-distribute-patterns -x c -c -o /dev/null - 2>/dev/null; then
  FLAGS="$FLAGS -fno-tree-loop-distribute-patterns"
fi
case "$("$CC" --version 2>/dev/null)" in
  *clang*) ;;
  *) FLAGS="$FLAGS -no-pie" ;;
esac

mkdir -p "$OUT/gen"
python3 "$SRC/gen_rows.py" "$OUT/gen/policy-rows.inc"
# shellcheck disable=SC2086
"$CC" $FLAGS -I"$SRC" -I"$OUT/gen" -o "$OUT/dn-init" \
  "$SRC/sys.c" "$SRC/catch.c" "$SRC/apply.c" "$SRC/gate.c" "$SRC/law.c"
# shellcheck disable=SC2086
"$CC" $FLAGS -o "$OUT/dn-substtest" "$SRC/substtest.c"
# shellcheck disable=SC2086
"$CC" $FLAGS -o "$OUT/dn-census" "$SRC/census.c"

# dn-exec: the gate hands every program to it (src/dn-exec/).  Not $FLAGS: it is
# a static PIE with its own entry, not a -static -nostdlib -e _start binary.
CC="$CC" GEN="$OUT/gen" sh "$ROOT/scripts/build-dn-exec.sh" "$OUT/dn-exec"

if command -v nm >/dev/null 2>&1; then
  for b in dn-init dn-exec; do
    n=$(nm -u "$OUT/$b" | wc -l)
    [ "$n" -eq 0 ] || { echo "build-runtime: $b imports $n symbols" >&2; exit 1; }
  done
fi
printf '%s\n' "$HOST" > "$OUT/host"
echo "build-runtime: $OUT/dn-init, dn-exec (host $HOST, $("$CC" -dumpversion 2>/dev/null || echo "$CC"))"
